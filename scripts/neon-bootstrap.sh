#!/usr/bin/env bash
#
# Brings a Neon Postgres project up to this build and writes the environment
# the hosted app needs.
#
# Run once, then again whenever the schema or the lessons change:
#
#   NEON_API_KEY=... ./scripts/neon-bootstrap.sh
#
# WHY NOT `neon login`: it signs in through a browser, which a headless agent
# session has no way to complete. An API key is the documented non-interactive
# path (`neon login --help`), and the CLI reads NEON_API_KEY from the
# environment without any further setup.
#
# WHY NOT `neon config init` + `neon deploy`: `neon deploy` applies a neon.ts
# policy describing services, functions and auth to a branch. It does not host
# a Next.js app, so it does not replace Vercel. The scaffolded policy also sets
# `auth: true`, which enables Neon Auth — a second identity system this app has
# no use for. Composer's Dungeon already authenticates with NextAuth against
# its own User table, bcrypt hashes and JWT sessions, and has its own password
# reset flow. Turning on Neon Auth beside that creates something nothing reads.
#
# This script therefore uses only the parts that apply: the project's
# connection strings, and the repo's own schema and seed scripts.
set -euo pipefail

PROJECT_ID="${NEON_PROJECT_ID:-royal-boat-29341408}"
BRANCH="${NEON_BRANCH:-production}"
OUT=".env.hosted.local"

if [ -z "${NEON_API_KEY:-}" ]; then
  cat >&2 <<'MSG'
NEON_API_KEY is not set.

Add it as a Network secret in the cloud environment settings (the environment
menu in the session title bar, then Edit), named exactly NEON_API_KEY, and
start a new session so it is picked up. Create the key itself in Neon under
Account settings -> API keys.
MSG
  exit 1
fi

command -v neon >/dev/null 2>&1 || npm i -g neon@latest

echo "[1/5] reading connection strings for $PROJECT_ID / $BRANCH"
# Two different strings for two different jobs. The direct one reaches Postgres
# itself and is the only one that can run DDL; a pooler cannot. The pooled one
# is what a serverless function must use at runtime, because a lambda has no
# business holding a real Postgres connection open.
DIRECT="$(neon connection-string "$BRANCH" --project-id "$PROJECT_ID")"
POOLED="$(neon connection-string "$BRANCH" --project-id "$PROJECT_ID" --pooled)"

# Prisma needs to be told the pooled endpoint is a pooler, and held to one
# connection per function instance.
case "$POOLED" in
  *\?*) RUNTIME="${POOLED}&pgbouncer=true&connection_limit=1" ;;
  *)    RUNTIME="${POOLED}?pgbouncer=true&connection_limit=1" ;;
esac

echo "[2/5] deriving the Postgres schema"
npm run --silent make:pg-schema
node scripts/check-schemas.mjs

echo "[3/5] bringing the database up to this build"
# Schema and seed both go through the DIRECT url.
export DATABASE_URL="$DIRECT"
export DIRECT_DATABASE_URL="$DIRECT"
export DATABASE_PROVIDER=postgresql
npm run --silent db:push:hosted
npx prisma generate --schema prisma/schema.postgres.prisma >/dev/null

echo "[4/5] seeding lessons, areas, bosses and exams"
npx tsx prisma/seed.ts

echo "[5/5] writing $OUT"
umask 077
cat > "$OUT" <<ENV
# Generated by scripts/neon-bootstrap.sh. Gitignored; holds live credentials.
# These are the variables to set on the host that runs the app.
DATABASE_URL=$RUNTIME
DIRECT_DATABASE_URL=$DIRECT
DATABASE_PROVIDER=postgresql
CD_HOSTED=1
NEXTAUTH_SECRET=$(openssl rand -base64 32)
# Set these two by hand before deploying:
#   NEXTAUTH_URL    the public URL players type, no trailing slash
#   CD_ADMIN_EMAIL  the address you sign up with; only that account may
#                   configure the mail sender, and without a sender nobody
#                   can reset a password
ENV

# Leave the working copy generated against SQLite, so desktop development and
# the 18 checkers keep working. Without this the repo is silently left on the
# Postgres client and every checker fails against prisma/dev.db.
npx prisma generate >/dev/null

echo
echo "Done. $OUT holds the connection strings and a fresh NEXTAUTH_SECRET."
echo "Still to set in it: NEXTAUTH_URL and CD_ADMIN_EMAIL."
